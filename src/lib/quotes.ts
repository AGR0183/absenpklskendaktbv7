export function getDailyQuote(date: Date = new Date()): Quote {
  const y = date.getFullYear();
  const m = date.getMonth() + 1;
  const d = date.getDate();
  const seed = y * 10000 + m * 100 + d;
  return QUOTES[seed % QUOTES.length];
}